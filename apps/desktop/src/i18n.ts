export type TranslationKey = keyof typeof korean;

export function resolveLocale(languages?: readonly string[]): Locale {
  const candidates = languages ??
    (typeof navigator === "undefined"
      ? []
      : navigator.languages?.length
        ? navigator.languages
        : [navigator.language]);
  for (const language of candidates) {
    const base = language.toLowerCase().split("-")[0];
    if (base === "ko" || base === "en") return base;
  }
  return "en";
}

export function t(key: TranslationKey, parameters: Parameters = {}): string {
  const template = resolveLocale() === "ko" ? korean[key] : key;
  return Object.entries(parameters).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template as string,
  );
}

export function localeTag(): string {
  return resolveLocale() === "ko" ? "ko-KR" : "en";
}
